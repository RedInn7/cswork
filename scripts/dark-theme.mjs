#!/usr/bin/env node
/**
 * Site-wide dark theme for the hand-written CSS (app/ and components/).
 *
 * Every stylesheet keeps its light colours where they are and gets a generated
 * `.dark`-scoped block appended at its end. The block repeats each colour-bearing
 * declaration (colour, background*, border*, outline*, shadows, fill/stroke) under
 * `.dark <selector>`: hard-coded colours are re-stepped for a dark surface, token
 * values (var(--…), currentColor) are copied as they are so the cascade picks the
 * same winner it picks in light mode. One extra class on every selector keeps all
 * specificity relationships intact.
 *
 * Mapping, in OKLCH (hue kept):
 * - light neutral backgrounds → dark surfaces (white → the raised card step,
 *   tinted fills invert so they still read as fills);
 * - dark text → light text, then nudged until it clears 4.5:1 on its surface;
 * - saturated or already-dark backgrounds (navy signs, amber chips, brand buttons)
 *   stay, and so does the text drawn on them;
 * - light hairlines → dark hairlines; dark neutral lines → light lines.
 * Hand-tuned values live in app/theme.css; any `.dark` selector + property set there
 * is left out of the generated blocks.
 *
 * After changing colours run `node scripts/dark-theme.mjs` (tests/dark-theme.test.mjs
 * fails while a block is stale or missing).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

export const START = '/* ── dark theme: generated by scripts/dark-theme.mjs, do not edit by hand ── */';
export const END = '/* ── end dark theme ── */';
const MANUAL = 'app/theme.css';

// ---------------------------------------------------------------- colour maths

const clamp = (x, lo = 0, hi = 1) => Math.min(hi, Math.max(lo, x));
const toLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLinear = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

/** sRGB 0..1 → OKLCH {L, C, H}. */
export function rgbToOklch([r, g, b]) {
  const [lr, lg, lb] = [r, g, b].map(toLinear);
  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  return { L, C: Math.hypot(A, B), H: ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360 };
}

function oklchToLinear({ L, C, H }) {
  const A = C * Math.cos((H * Math.PI) / 180);
  const B = C * Math.sin((H * Math.PI) / 180);
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

/** OKLCH → sRGB 0..1, lowering chroma until the colour fits the sRGB gamut. */
export function oklchToRgb(c) {
  let C = c.C;
  for (let i = 0; i < 40; i++) {
    const lin = oklchToLinear({ ...c, C });
    if (lin.every((v) => v >= -1e-4 && v <= 1 + 1e-4)) return lin.map((v) => clamp(fromLinear(clamp(v))));
    C *= 0.92;
  }
  return oklchToLinear({ ...c, C: 0 }).map((v) => clamp(fromLinear(clamp(v))));
}

/** WCAG relative luminance of sRGB 0..1. */
export const luminance = ([r, g, b]) =>
  0.2126 * toLinear(r) + 0.7152 * toLinear(g) + 0.0722 * toLinear(b);
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const NAMED = { white: [1, 1, 1], black: [0, 0, 0] };
const num = (s, scale = 1) => (s.endsWith('%') ? (parseFloat(s) / 100) * scale : parseFloat(s));

function hslToRgb(h, s, l) {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  return [0, 8, 4].map((n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)));
}

/** Parse one CSS colour literal → {rgb: [0..1]x3, alpha} or null. */
export function parseColor(text) {
  const t = text.trim().toLowerCase();
  if (t in NAMED) return { rgb: NAMED[t], alpha: 1 };
  if (t.startsWith('#')) {
    let h = t.slice(1);
    if (h.length === 3 || h.length === 4) h = [...h].map((x) => x + x).join('');
    if (h.length !== 6 && h.length !== 8) return null;
    const v = [0, 2, 4, 6].map((i) => parseInt(h.slice(i, i + 2), 16));
    return { rgb: v.slice(0, 3).map((x) => x / 255), alpha: h.length === 8 ? v[3] / 255 : 1 };
  }
  const fn = /^(rgba?|hsla?|oklch)\((.*)\)$/.exec(t);
  if (!fn || /var\(|calc\(|from /.test(fn[2])) return null;
  const parts = fn[2].replace(/\//, ' / ').split(/[\s,]+/).filter(Boolean);
  const slash = parts.indexOf('/');
  const values = slash >= 0 ? parts.slice(0, slash) : parts.slice(0, 3);
  const alphaText = slash >= 0 ? parts[slash + 1] : parts[3];
  const alpha = alphaText === undefined ? 1 : clamp(num(alphaText));
  if (values.length < 3) return null;
  if (fn[1].startsWith('rgb')) return { rgb: values.map((v) => clamp(num(v, 255) / 255)), alpha };
  if (fn[1].startsWith('hsl'))
    return { rgb: hslToRgb(parseFloat(values[0]), num(values[1], 1), num(values[2], 1)), alpha };
  const L = num(values[0]);
  return { rgb: oklchToRgb({ L, C: num(values[1], 0.4), H: parseFloat(values[2]) || 0 }), alpha };
}

const hex2 = (x) => Math.round(clamp(x) * 255).toString(16).padStart(2, '0');
export function formatColor({ rgb, alpha }) {
  const base = '#' + rgb.map(hex2).join('');
  return alpha >= 0.999 ? base : base + hex2(alpha);
}

// ---------------------------------------------------------------- the mapping

/** The surface text is assumed to sit on when its own rule sets none (a mapped tinted fill). */
export const REFERENCE_SURFACE = oklchToRgb({ L: 0.3, C: 0, H: 0 });

const withL = (o, L, C = o.C) => oklchToRgb({ L: clamp(L), C, H: o.H });

/**
 * Light neutral background → dark surface. Near-white keeps its order (white cards sit
 * one step above an off-white page, hovers dip below the card); stronger tints invert
 * so a filled chip or selected row still reads as filled.
 */
export function surfaceL(L) {
  return L >= 0.95 ? 0.215 - (1 - L) * 0.8 : 0.175 + (0.95 - L) * 0.6;
}
const surface = (o) => withL(o, surfaceL(o.L), Math.min(o.C * 0.8, 0.045));

/** Light hairline → dark hairline. */
const hairline = (o) => withL(o, Math.min(0.4, 0.27 + (0.99 - o.L) * 0.5), Math.min(o.C, 0.05));

/** Text → light text that clears 4.5:1 against `ground`. */
export function lightText(rgb, ground = REFERENCE_SURFACE) {
  const o = rgbToOklch(rgb);
  let L = o.L < 0.6 ? 0.78 + (0.6 - o.L) * 0.35 : Math.max(o.L, 0.76);
  const C = o.C * 0.85;
  let out = withL(o, L, C);
  while (contrast(out, ground) < 4.6 && L < 1) {
    L = Math.min(1, L + 0.02);
    out = withL(o, L, C);
  }
  return out;
}

/**
 * Map one parsed colour for a role:
 * 'bg' | 'border' | 'shadow' | 'text' | 'fill' | 'stroke' | 'keep'.
 * Returns {rgb, alpha} (possibly unchanged).
 */
export function mapColor(color, role, ground) {
  const { rgb, alpha } = color;
  const o = rgbToOklch(rgb);
  // Accents (and mid-light accents like progress fills) keep their colour; pastel tints do not.
  const saturated = o.C >= 0.1 || (o.C >= 0.07 && o.L < 0.9);
  const same = color;
  switch (role) {
    case 'bg':
      if (alpha < 0.35) {
        // Faint overlays: a dark hover tint becomes a light one; light speckles stay.
        if (o.L < 0.35 && !saturated && alpha <= 0.12) return { rgb: [1, 1, 1], alpha };
        return same;
      }
      if (saturated || o.L < 0.75) return same;
      return { rgb: surface(o), alpha };
    case 'border':
      // Pastel lines (a light amber box edge) dim with the rest; vivid ones stay.
      if (o.C >= 0.12 || (o.C >= 0.07 && o.L < 0.8)) return same;
      if (o.L >= 0.75) return alpha < 0.35 ? same : { rgb: hairline(o), alpha };
      if (o.L < 0.45) {
        if (alpha < 0.35) return { rgb: [1, 1, 1], alpha };
        return { rgb: withL(o, 0.62 + (0.45 - o.L) * 0.4), alpha };
      }
      return same;
    case 'shadow':
      if (!saturated && o.L >= 0.75 && alpha >= 0.35) return { rgb: hairline(o), alpha };
      return same;
    case 'text':
      return { rgb: lightText(rgb, ground), alpha };
    case 'fill':
    case 'stroke':
      if (saturated) return same;
      if (o.L >= 0.75) return { rgb: role === 'fill' ? surface(o) : hairline(o), alpha };
      if (o.L < 0.6) return { rgb: lightText(rgb), alpha };
      return same;
    default:
      return same;
  }
}

// A colour literal inside a value: hex, rgb()/hsl()/oklch(), or the white/black keywords.
const COLOR_RE =
  /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch)\([^()]*\)|(?<![\w-])(?:white|black)(?![\w-])/g;

export const hasColorLiteral = (value) => {
  COLOR_RE.lastIndex = 0;
  return COLOR_RE.test(value.replace(/url\([^)]*\)/g, ''));
};

function mapValue(value, role, ground) {
  return value.replace(COLOR_RE, (match) => {
    const parsed = parseColor(match);
    return parsed ? formatColor(mapColor(parsed, role, ground)) : match;
  });
}

// Tokens app/theme.css turns light in dark mode: text drawn on them needs dark ink.
const LIGHT_ACCENT = /var\(--(primary|sidebar-primary|verdict-(ac|tle|wa)|destructive|ring|rd-brand|rd-sky|cs-blue)\)/;
const SURFACE_TOKEN = /var\(--(background|card|popover|muted|secondary|accent|sidebar|input|rd-surface|rd-fill[\w-]*|cs-surface[\w-]*|cs-canvas)\)/;
export const DARK_INK = '#0b1411';

const BG_PROPS = /^background(-color|-image)?$/;
const TEXT_PROPS = /^(color|-webkit-text-fill-color|caret-color|text-decoration(-color)?|text-emphasis-color)$/;
const SHADOW_PROPS = /^(box-shadow|text-shadow)$/;
const BORDER_PROPS = /^(border(-(top|right|bottom|left|block|inline)(-(start|end))?)?(-color|-style|-width)?|border-image.*|outline(-color|-style|-width)?|column-rule(-color)?)$/;
const FILL_PROPS = /^(fill|stop-color|flood-color|lighting-color)$/;
const STROKE_PROPS = /^(stroke|scrollbar-color|accent-color)$/;

/** Which declarations the dark block repeats, and in which colour role. */
export function roleOf(prop) {
  if (/^background/.test(prop)) return BG_PROPS.test(prop) ? 'bg' : 'copy';
  if (TEXT_PROPS.test(prop)) return 'text';
  if (SHADOW_PROPS.test(prop)) return 'shadow';
  if (BORDER_PROPS.test(prop)) return 'border';
  if (FILL_PROPS.test(prop)) return 'fill';
  if (STROKE_PROPS.test(prop)) return 'stroke';
  return null;
}

/** Custom properties: the role is read off the name; unknown names (accents, signs) stay. */
export function customRole(name) {
  const n = name.replace(/^--/, '');
  if (/(^|-)(border|line|rule|hair|hairline|divider|ring|stroke|grid|edge|outline)(-|$)/.test(n))
    return 'border';
  if (/(^|-)(ink|text|fg|foreground|muted|subtle|label|title|heading|copy)(-|\d|$)/.test(n)) return 'text';
  if (/(^|-)(bg|background|page|surface|canvas|paper|card|panel|fill|soft|tint|wash|sheet|popover|well|track|chip)(-|\d|$)/.test(n))
    return 'bg';
  return 'keep';
}

// ---------------------------------------------------------------- per-file generation

const SKIP_AT = new Set(['keyframes', 'font-face', 'import', 'charset', 'layer', 'theme', 'custom-variant',
  'source', 'utility', 'variant', 'plugin', 'config', 'reference', 'page', 'property', 'tailwind', 'apply']);
const skipMedia = (params) => /print|forced-colors|prefers-color-scheme/.test(params);

// Parts that already carry their own dark styling.
const DARK_SCOPED = /\[data-theme=['"]?dark|(^|[\s,])(html|:root)?\.dark(?![\w-])/;

/** `.a .b:hover` → `.dark .a .b:hover`; `:root`/`html` take the class themselves. */
export function prefixSelector(sel) {
  const s = sel.trim();
  if (/^(:root|html)(?![\w-])/.test(s)) return s.replace(/^(:root|html)/, '$1.dark');
  return `.dark ${s}`;
}

/** Remove an earlier generated block so the file can be regenerated. */
export function stripBlock(css) {
  const i = css.indexOf(START);
  if (i < 0) return css;
  const j = css.indexOf(END, i);
  return (css.slice(0, i).replace(/\s+$/, '\n') + (j < 0 ? '' : css.slice(j + END.length).replace(/^\s+/, ''))).replace(/\n*$/, '\n');
}

/** Classify a background value: what will the dark block do to the surface behind text? */
function bgClass(value, vars) {
  const resolved = value.replace(/var\((--[\w-]+)\)/g, (m, name) => (vars.has(name) && !LIGHT_ACCENT.test(m) && !SURFACE_TOKEN.test(m) ? vars.get(name) : m));
  if (LIGHT_ACCENT.test(resolved)) return { kind: 'accent' };
  // Tints mixed with transparent are faint overlays, not the surface behind text.
  const opaque = resolved
    .replace(/url\([^)]*\)/g, '')
    .replace(/color-mix\((?:[^()]|\([^()]*\))*\)/g, (m) =>
      m.includes('transparent') ? '' : SURFACE_TOKEN.test(m) ? 'var(--card)' : m,
    );
  const literals = (opaque.match(COLOR_RE) || []).map(parseColor).filter(Boolean);
  const solid = literals.filter((c) => c.alpha >= 0.35);
  if (solid.length) {
    const mapped = solid.map((c) => mapColor(c, 'bg'));
    if (mapped.some((m, i) => m !== solid[i])) return { kind: 'surface', ground: mapped.find((m, i) => m !== solid[i]).rgb };
    return { kind: 'keep', dark: solid.every((c) => rgbToOklch(c.rgb).L < 0.5) };
  }
  if (SURFACE_TOKEN.test(resolved)) return { kind: 'surface' };
  return null;
}

const PSEUDO = /::?[\w-]+(\([^)]*\))?/g;
const compounds = (sel) => sel.replace(PSEUDO, '').trim().split(/\s*[\s>+~]\s*/).filter(Boolean);
const groundKey = (sel) => compounds(sel).join(' ');

/**
 * Where to look up the background behind a selector's element: first the element
 * itself (`.a .b.c` → `.a .b.c`, `.b.c`, `.b`, `.c`), then its ancestors nearest first.
 */
export function contexts(sel) {
  const parts = compounds(sel);
  const self = [];
  const above = [];
  for (let i = parts.length; i > 0; i--) {
    const list = i === parts.length ? self : above;
    list.push(parts.slice(0, i).join(' '), parts[i - 1], ...(parts[i - 1].match(/[.#][\w-]+/g) ?? []));
  }
  return { self: [...new Set(self)], above: [...new Set(above)] };
}

/**
 * Build the generated dark block for one stylesheet (without markers).
 * `manual` is a Set of `selector|prop` already hand-set in app/theme.css.
 */
export function darkBlock(css, { manual = new Set(), from } = {}) {
  const root = postcss.parse(stripBlock(css), { from });
  // Custom properties as the light theme first defines them, for resolving var(--x) backgrounds.
  const vars = new Map();
  root.walkDecls(/^--/, (d) => {
    if (!vars.has(d.prop) && !DARK_SCOPED.test(d.parent.selector ?? '')) vars.set(d.prop, d.value);
  });
  // Which selectors paint a background, and what the dark block does to it.
  const grounds = new Map();
  root.walkRules((rule) => {
    const bgs = rule.nodes.filter((n) => n.type === 'decl' && BG_PROPS.test(n.prop));
    const cls = bgs.map((d) => bgClass(d.value, vars)).filter(Boolean).at(-1);
    // Only resting states paint the ground: `.x:hover` / `:has(:checked)` must not stand in for `.x`.
    if (cls) for (const sel of rule.selectors) if (!sel.includes(':')) grounds.set(groundKey(sel), cls);
  });

  const out = postcss.root();
  const copy = (node, parent) => {
    if (node.type === 'atrule') {
      if (SKIP_AT.has(node.name) || (node.name === 'media' && skipMedia(node.params))) return;
      if (!node.nodes) return;
      const at = postcss.atRule({ name: node.name, params: node.params });
      node.each((child) => copy(child, at));
      if (at.nodes?.length) parent.append(at);
      return;
    }
    if (node.type !== 'rule') return;
    if (node.parent?.type === 'atrule' && node.parent.name === 'keyframes') return;
    const selectors = node.selectors.filter((s) => !/^\s*(\.dark|html\.dark|:root\.dark)(?![\w-])/.test(s));
    if (!selectors.length) return;
    const prefixed = selectors.map(prefixSelector);
    // The rule's own background, else the nearest ancestor rule's in this file.
    const own = node.nodes
      .filter((n) => n.type === 'decl' && BG_PROPS.test(n.prop))
      .map((d) => bgClass(d.value, vars))
      .filter(Boolean)
      .at(-1);
    const lookup = (key) =>
      selectors.map((s) => contexts(s)[key].map((c) => grounds.get(c)).find(Boolean)).find(Boolean);
    const self = own ?? lookup('self');
    const inherited = lookup('above');
    const context = self ?? inherited;
    // A dark island (navy sign, dark hero) is already dark: it and everything in it stay as designed.
    // So is a part with its own dark styling (the editor workbench's data-theme='dark').
    const frozen =
      [self, inherited].some((c) => c?.kind === 'keep' && c.dark) ||
      selectors.some((s) => DARK_SCOPED.test(s));
    const decls = [];
    for (const d of node.nodes) {
      if (d.type !== 'decl') continue;
      const custom = d.prop.startsWith('--');
      const role = custom ? (hasColorLiteral(d.value) ? customRole(d.prop) : null) : roleOf(d.prop);
      if (!role || (custom && role === 'keep')) continue;
      if (/url\(/.test(d.value)) continue; // images: relative paths and nothing to re-colour
      if (prefixed.every((s) => manual.has(`${s.replace(/\s+/g, ' ')}|${d.prop}`))) continue;
      let value = d.value;
      if (frozen) {
        // copied as is, so the cascade still prefers it over mapped rules
      } else if (role === 'text' && !custom) {
        if (context?.kind === 'accent') {
          value = value.replace(COLOR_RE, (m) => {
            const c = parseColor(m);
            return c && rgbToOklch(c.rgb).L > 0.85 ? DARK_INK : m;
          });
        } else if (context?.kind !== 'keep') {
          value = mapValue(value, 'text', context?.ground);
        }
      } else if (role !== 'copy' && role !== 'keep') {
        value = mapValue(value, role);
      }
      decls.push(postcss.decl({ prop: d.prop, value, important: d.important }));
    }
    if (!decls.length) return;
    const rule = postcss.rule({ selectors: prefixed });
    rule.append(decls);
    parent.append(rule);
  };
  root.each((node) => copy(node, out));
  if (!out.nodes.length) return '';
  out.walk((n) => {
    n.raws.before = n.parent === out ? '\n' : '\n' + '  '.repeat(depth(n));
    if (n.type !== 'decl') n.raws.after = '\n' + '  '.repeat(depth(n));
    if (n.type === 'rule') n.selector = n.selectors.join(',\n' + '  '.repeat(depth(n)));
    if (n.type === 'decl') n.raws.between = ': ';
    else n.raws.between = ' ';
    if (n.type !== 'decl') n.raws.semicolon = true;
  });
  return out.toString().trim();
}
function depth(n) {
  let d = 0;
  for (let p = n.parent; p && p.type !== 'root'; p = p.parent) d++;
  return d;
}

/** The whole stylesheet with its generated block brought up to date. */
export function withDarkBlock(css, options) {
  const base = stripBlock(css);
  const block = darkBlock(base, options);
  return block ? `${base.replace(/\n*$/, '\n')}\n${START}\n${block}\n${END}\n` : base;
}

/** `selector|prop` pairs hand-set in app/theme.css. */
export function manualKeys(css) {
  const keys = new Set();
  postcss.parse(css).walkDecls((d) => {
    if (d.parent.type !== 'rule') return;
    for (const s of d.parent.selectors) keys.add(`${s.trim().replace(/\s+/g, ' ')}|${d.prop}`);
  });
  return keys;
}

/** Stylesheets that get a block: plain CSS under app/ and components/. */
export function themedFiles(dir) {
  const found = [];
  const walk = (rel) => {
    for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const p = path.posix.join(rel, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (p.endsWith('.css') && !p.endsWith('.module.css') && p !== MANUAL) found.push(p);
    }
  };
  for (const top of ['app', 'components']) if (fs.existsSync(path.join(dir, top))) walk(top);
  return found.sort();
}

export function regenerate(dir, { check = false } = {}) {
  const manual = manualKeys(fs.readFileSync(path.join(dir, MANUAL), 'utf8'));
  const stale = [];
  for (const file of themedFiles(dir)) {
    const full = path.join(dir, file);
    const css = fs.readFileSync(full, 'utf8');
    const next = withDarkBlock(css, { manual, from: full });
    if (next === css) continue;
    stale.push(file);
    if (!check) fs.writeFileSync(full, next);
  }
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const check = process.argv.includes('--check');
  const stale = regenerate(dir, { check });
  if (check && stale.length) {
    console.error(`Dark theme blocks are stale in:\n  ${stale.join('\n  ')}\nRun: node scripts/dark-theme.mjs`);
    process.exit(1);
  }
  console.log(check ? 'Dark theme blocks are up to date.' : `Updated ${stale.length} stylesheet(s).`);
}
